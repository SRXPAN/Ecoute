# Windows API constants for stealth mode
WDA_EXCLUDEFROMCAPTURE = 0x00000011
GWL_EXSTYLE = -20
WS_EX_APPWINDOW = 0x00040000
WS_EX_TOOLWINDOW = 0x00000080

# Global flags for tracking generation and visibility status
is_generating = False
is_hidden = False
main_window = None
overlay_mgr = None
transcriber_global = None  # For hotkey access

def save_interview_log(transcriber):
    """
    Save the current interview transcript to a markdown file in interviews/ directory.
    Format: Speaker questions with clean markdown headers.
    """
    try:
        # Create interviews directory if it doesn't exist
        if not os.path.exists("interviews"):
            os.makedirs("interviews")
            print("[INFO] Created interviews/ directory")

        # Generate timestamp filename
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        filename = f"interviews/interview_{timestamp}.md"

        # Get transcript data
        transcript = transcriber.get_transcript()

        if not transcript or len(transcript.strip()) < 10:
            print("[INFO] No transcript data to save")
            return None

        # Format as markdown with clean headers
        markdown_content = f"""# Interview Session - {datetime.now().strftime("%Y-%m-%d %H:%M:%S")}

## Transcript

{transcript}

---
*Generated by AI Copilot Pro*
"""

        # Write to file
        with open(filename, "w", encoding="utf-8") as f:
            f.write(markdown_content)

        print(f"[INFO] Interview log saved: {filename}")
        return filename

    except Exception as e:
        print(f"[ERROR] Failed to save interview log: {e}")
        return None

def toggle_app_visibility():
    """
    Global hotkey handler (Ctrl+Shift+H) to hide/show all application windows.
    Uses root.after() for thread-safety with Tkinter.
    """
    global is_hidden, main_window, overlay_mgr

    def _toggle():
        global is_hidden

        if is_hidden:
            # Restore windows
            if main_window:
                main_window.deiconify()
            if overlay_mgr and overlay_mgr.overlay:
                overlay_mgr.overlay.show_overlay()
            is_hidden = False
            print("[INFO] Application windows RESTORED (Ctrl+Shift+H)")
        else:
            # Hide windows
            if main_window:
                main_window.withdraw()
            if overlay_mgr and overlay_mgr.overlay:
                overlay_mgr.overlay.hide_overlay()
            is_hidden = True
            print("[INFO] Application windows HIDDEN (Ctrl+Shift+H)")

    # Execute in Tkinter's main thread for safety
    if main_window:
        main_window.after(0, _toggle)

def hotkey_clear_session():
    """
    Global hotkey handler (Ctrl+Shift+C) to clear session and save log.
    Saves transcript, clears data, resets LLM, and clears UI.
    """
    global main_window, transcriber_global, overlay_mgr

    def _clear():
        if transcriber_global:
            print("[INFO] Hotkey triggered: Clearing session (Ctrl+Shift+C)")

            # Save interview log before clearing
            save_interview_log(transcriber_global)

            # Clear transcript data
            transcriber_global.clear_transcript_data()

            # Clear overlay cards
            if overlay_mgr and overlay_mgr.overlay:
                try:
                    for widget in overlay_mgr.overlay.cards_container.winfo_children():
                        widget.destroy()
                except:
                    pass

    if main_window:
        main_window.after(0, _clear)

def panic_button():
    """
    Emergency exit hotkey (Ctrl+Alt+End) - instantly kills the application.
    No cleanup, no saving, immediate termination.
    """
    print("[PANIC] Emergency exit triggered (Ctrl+Alt+End)")
    os._exit(0)

def apply_total_stealth(window):
    """
    Apply complete stealth mode to the main window:
    1. Hide from screen capture (Zoom, Teams, OBS)
    2. Hide from Windows Taskbar
    3. Hide from Alt+Tab menu
    """
    try:
        window.update()
        hwnd = ctypes.windll.user32.GetParent(window.winfo_id())

        if hwnd:
            # 1. Exclude from screen capture
            result = ctypes.windll.user32.SetWindowDisplayAffinity(hwnd, WDA_EXCLUDEFROMCAPTURE)
            if result:
                print("[INFO] Main window excluded from screen capture")
            else:
                print("[WARNING] Failed to exclude main window from screen capture")

            # 2. Hide from Taskbar and Alt+Tab
            ex_style = ctypes.windll.user32.GetWindowLongW(hwnd, GWL_EXSTYLE)
            new_style = (ex_style & ~WS_EX_APPWINDOW) | WS_EX_TOOLWINDOW
            ctypes.windll.user32.SetWindowLongW(hwnd, GWL_EXSTYLE, new_style)

            # Force window to update its style
            window.withdraw()
            window.deiconify()

            print("[INFO] Main window hidden from Taskbar and Alt+Tab")
        else:
            print("[WARNING] Could not get window handle for stealth mode")

    except Exception as e:
        print(f"[ERROR] Failed to apply total stealth: {e}")

def write_in_textbox(textbox, text):
    textbox.delete("0.0", "end")
    textbox.insert("0.0", text)

def update_transcript_UI(transcriber, transcript_textbox, suggestion_textbox, llm_client, overlay_manager, status_indicator):
    global is_generating

    # Update status indicators in real-time
    speaker_status = transcriber.get_statuses()
    status_indicator.configure(text=f"{speaker_status} Speaker")

    # Update transcript
    transcript_string = transcriber.get_transcript()
    write_in_textbox(transcript_textbox, transcript_string)

    latest_speaker_text = transcriber.get_latest_speaker_text()
    if latest_speaker_text and len(latest_speaker_text.strip()) > 20:
        if not hasattr(update_transcript_UI, 'last_processed') or update_transcript_UI.last_processed != latest_speaker_text:

            if not is_generating:
                update_transcript_UI.last_processed = latest_speaker_text
                is_generating = True

                def thread_target():
                    global is_generating
                    try:
                        get_ai_suggestion(latest_speaker_text, suggestion_textbox, llm_client, overlay_manager)
                    finally:
                        is_generating = False

                threading.Thread(target=thread_target, daemon=True).start()

    transcript_textbox.after(300, update_transcript_UI, transcriber, transcript_textbox, suggestion_textbox, llm_client, overlay_manager, status_indicator)

def get_ai_suggestion(interviewer_question, suggestion_textbox, llm_client, overlay_manager):
    try:
        suggestion_textbox.delete("0.0", "end")
        suggestion_textbox.insert("0.0", "🤔 Analyzing question...\n")

        full_response = ""
        response_generator = llm_client.get_suggestion(interviewer_question)

        # Create a new Q&A card in the overlay
        answer_box = overlay_manager.overlay.add_qa_card(interviewer_question)

        # Clear "Thinking..." message
        answer_box.configure(state="normal")
        answer_box.delete("0.0", "end")
        answer_box.configure(state="disabled")

        # Stream tokens to both dashboard and overlay card
        for token in response_generator:
            full_response += token

            # Update dashboard
            suggestion_textbox.delete("0.0", "end")
            suggestion_textbox.insert("0.0", full_response)
            suggestion_textbox.update()

            # Stream to overlay card
            answer_box.configure(state="normal")
            answer_box.insert("end", token)
            answer_box.see("end")
            answer_box.configure(state="disabled")
            answer_box.update()

    except Exception as e:
        print(f"[ERROR] Failed to get AI suggestion: {e}")
        suggestion_textbox.delete("0.0", "end")
        suggestion_textbox.insert("0.0", "❌ AI suggestion failed")

        # Update overlay card if it exists
        if 'answer_box' in locals():
            answer_box.configure(state="normal")
            answer_box.delete("0.0", "end")
            answer_box.insert("0.0", "❌ AI suggestion failed")
            answer_box.configure(state="disabled")

def clear_context(transcriber, suggestion_textbox, llm_client, overlay_manager):
    # Save interview log before clearing
    save_interview_log(transcriber)

    transcriber.clear_transcript_data()

    suggestion_textbox.delete("0.0", "end")
    suggestion_textbox.insert("0.0", "Ready for next question...")
    llm_client.reset_conversation()

    # Clear all cards in overlay
    if overlay_manager.overlay:
        for widget in overlay_manager.overlay.cards_container.winfo_children():
            widget.destroy()

    if hasattr(update_transcript_UI, 'last_processed'):
        delattr(update_transcript_UI, 'last_processed')

