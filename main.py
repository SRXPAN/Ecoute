def toggle_pause(transcriber, pause_button):
    """Toggle pause state and update button appearance"""
    is_paused = transcriber.toggle_pause()

    if is_paused:
        pause_button.configure(
            text="▶️ Resume AI Listening",
            fg_color="#10B981",
            hover_color="#059669"
        )
    else:
        pause_button.configure(
            text="⏸️ Pause AI Listening",
            fg_color="#EF4444",
            hover_color="#DC2626"
        )

def main():
    global main_window, overlay_mgr, transcriber_global

    load_dotenv()

    # Create interviews directory on startup
    if not os.path.exists("interviews"):
        os.makedirs("interviews")
        print("[INFO] Created interviews/ directory for logs")

    speaker_device_index = os.getenv("SPEAKER_DEVICE_INDEX")

    if speaker_device_index:
        speaker_device_index = int(speaker_device_index)
    else:
        speaker_device_index = None

    context_file = "temp_context.txt"
    if os.path.exists(context_file):
        with open(context_file, "r", encoding="utf-8") as f:
            interview_context = f.read()
            print(f"[INFO] Loaded interview context ({len(interview_context)} characters)")
    else:
        interview_context = ""
        print("[INFO] No interview context found")

    # Load AI persona from environment
    ai_persona = os.getenv("AI_PERSONA", "Short Bullets")
    print(f"[INFO] AI Persona: {ai_persona}")

    try:
        llm_client = LLMClient(provider="local", persona=ai_persona)
        print("[INFO] LLM client initialized successfully")
    except Exception as e:
        print(f"[ERROR] Failed to initialize LLM client: {e}")
        print("[WARNING] Continuing without AI suggestions")
        llm_client = None

    root = ctk.CTk()
    main_window = root  # Store reference for global hotkey

    # Apply total stealth mode to main window
    apply_total_stealth(root)

    def cleanup_on_exit():
        print("[INFO] Cleaning up and saving interview log...")
        try:
            # Save interview log before exit
            if transcriber_global:
                save_interview_log(transcriber_global)

            if os.path.exists("temp_context.txt"):
                os.remove("temp_context.txt")
                print("[INFO] Removed temp_context.txt")
        except Exception as e:
            print(f"[WARNING] Failed to cleanup: {e}")

    def hard_exit():
        print("[INFO] Application closing...")
        cleanup_on_exit()
        try:
            if transcriber_global:
                transcriber_global.close()
        except:
            pass
        if main_window:
            main_window.quit()
            main_window.destroy()

    overlay_manager = StealthOverlayManager()
    overlay_mgr = overlay_manager  # Store reference for global hotkey
    overlay_manager.create_overlay()
    print("[INFO] Stealth overlay created")

    # Register global hotkeys in a daemon thread to avoid blocking
    def register_hotkeys():
        try:
            keyboard.add_hotkey('ctrl+shift+h', toggle_app_visibility)
            print("[INFO] Global hotkey registered: Ctrl+Shift+H to toggle visibility")

            keyboard.add_hotkey('ctrl+shift+c', hotkey_clear_session)
            print("[INFO] Global hotkey registered: Ctrl+Shift+C to clear session")

            keyboard.add_hotkey('ctrl+alt+end', panic_button)
            print("[INFO] Global hotkey registered: Ctrl+Alt+End for emergency exit")
        except Exception as e:
            print(f"[WARNING] Failed to register global hotkeys: {e}")
            print("[WARNING] Hotkeys require administrator privileges on Windows")

    # Register hotkeys in background thread
    hotkey_thread = threading.Thread(target=register_hotkeys, daemon=True)
    hotkey_thread.start()

    try:
        speaker_recorder = AudioRecorder.DefaultSpeakerRecorder(device_index=speaker_device_index)

        transcriber = AudioTranscriber(speaker_recorder)
        transcriber_global = transcriber  # Store for hotkey access
        transcriber.start()

        root.protocol("WM_DELETE_WINDOW", hard_exit)

        transcript_textbox, suggestion_textbox, status_indicator = create_ui_components(root, transcriber, llm_client, overlay_manager)

        print("READY")

        if llm_client:
            update_transcript_UI(transcriber, transcript_textbox, suggestion_textbox, llm_client, overlay_manager, status_indicator)
        else:
            def update_transcript_no_llm():
                transcript_string = transcriber.get_transcript()
                write_in_textbox(transcript_textbox, transcript_string)
                transcript_textbox.after(300, update_transcript_no_llm)
            update_transcript_no_llm()

        root.mainloop()

    except Exception as e:
        print(f"[ERROR] Failed to initialize audio system: {e}")

        root.protocol("WM_DELETE_WINDOW", lambda: (cleanup_on_exit(), root.quit(), root.destroy()))

        transcript_textbox, suggestion_textbox, status_indicator = create_ui_components(root, None, llm_client, overlay_manager)

        error_message = f"❌ Audio Initialization Failed\n\n{str(e)}\n\nPossible causes:\n• Invalid audio device selected\n• Audio device disconnected\n• Sample rate not supported\n\nPlease restart and select different audio devices."
        write_in_textbox(transcript_textbox, error_message)
        write_in_textbox(suggestion_textbox, "Audio system unavailable")

        root.mainloop()

if __name__ == "__main__":
    main()
